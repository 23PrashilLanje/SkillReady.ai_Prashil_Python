## 5th TUPLE SLICING   ###

nums = (10, 20, 30, 40, 50, 60)
 
print(nums[1:4])    # (20, 30, 40)
print(nums[:3])     # (10, 20, 30)
print(nums[3:])     # (40, 50, 60)
print(nums[::2])    # (10, 30, 50)  step jumps
print(nums[::-1])   # (60, 50, 40, 30, 20, 10)  REVERSED


